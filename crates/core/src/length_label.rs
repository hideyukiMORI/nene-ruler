//! 枠に出す長さの数字の種類（FR-004 / FR-007・ADR 0017）。

/// 幅・高さ・両方。閉じた集合。表示・当たり判定・コピーはこの単位で行う。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LengthLabel {
    /// 幅（`400 px`）。上辺の目盛の数字の下の中央。
    Width,
    /// 高さ（`240 px`）。左辺の目盛の数字の右の中央に、90 度回して置く。
    Height,
    /// 幅と高さ（`100 × 20 px`）。詰めた表示のとき、枠の中央に 1 行で置く。
    Size,
}
