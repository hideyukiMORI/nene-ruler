//! 枠をどこまで描くか（ADR 0017）。

/// 目盛と数字を全部描くか、詰めて線と `W × H px` だけにするか、線も消して文字だけ見せるか。閉じた集合。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FrameDetail {
    /// 目盛・目盛の数字・幅と高さの数字・通知を描く。
    Full,
    /// 幅と高さの数字が目盛を避けた内側に収まらない。目盛と通知を描かず、中央に `W × H px`。
    Compact,
    /// 詰めても `W × H px` が枠の内側に収まらない。線を描かず、鉤括弧を細くし、
    /// `W × H px` を窓の横の中央に置いて枠の外へはみ出して描く（ADR 0018）。掴める範囲は変えない。
    Bare,
}
